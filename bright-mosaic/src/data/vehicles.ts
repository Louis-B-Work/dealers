// The "from" monthly figure is the longest term we quote with no deposit,
// which is what makes it a *from* price.
export const vehicles: Vehicle[] = vehicleList.map((v) => ({
  ...v,
  monthlyFrom: v.price > 0 ? monthlyPaymentFor(v.price) : 0,
  image: VEHICLE_PHOTOS[v.id] ?? PLACEHOLDER_CAR_IMAGE,
}))

export function getVehicleById(id: string): Vehicle | undefined {
  return vehicles.find((v) => v.id === id)
}
